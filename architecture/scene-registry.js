// Deterministic semantic-scene registry. Pure JavaScript; no UI, Three.js or network.
import {validateScene} from './contracts.js';
const defaults={
 concept:{layout:'cards',renderer:'spatial-panels',fallback:'accessible-list'},
 comparison:{layout:'aligned',renderer:'comparison',fallback:'table'},
 timeline:{layout:'time-axis',renderer:'timeline',fallback:'chronological-list'},
 process:{layout:'directed',renderer:'flow',fallback:'ordered-list'},
 network:{layout:'graph',renderer:'network',fallback:'adjacency-list'},
 chart:{layout:'data',renderer:'chart',fallback:'table'},
 table:{layout:'grid',renderer:'html-table',fallback:'html-table'},
 model:{layout:'fit-bounds',renderer:'gltf',fallback:'model-metadata'},
 media:{layout:'aspect',renderer:'media',fallback:'media-description'}
};
export class SceneRegistry{
 #types=new Map();
 constructor(){for(const [type,config] of Object.entries(defaults))this.register(type,config)}
 register(type,config){
  if(typeof type!=='string'||!type||this.#types.has(type))throw Error('Duplicate or invalid scene type');
  if(!config||!config.layout||!config.renderer||!config.fallback)throw Error('Scene adapter requires layout, renderer, fallback');
  this.#types.set(type,Object.freeze({...config}));return this;
 }
 get(type){return this.#types.get(type)||null}
 list(){return [...this.#types.keys()]}
 compile(scene,evidenceIds=new Set()){
  const validation=validateScene(scene,evidenceIds);if(!validation.ok)return {ok:false,errors:validation.errors};
  const adapter=this.get(scene.type);if(!adapter)return {ok:false,errors:['No renderer for '+scene.type]};
  // Only semantic instructions. Geometry is generated by the selected layout adapter.
  const plan={version:1,sceneId:scene.id,kind:scene.type,title:String(scene.title||''),
   renderer:adapter.renderer,layout:adapter.layout,fallback:adapter.fallback,
   nodes:scene.nodes.map(n=>({...n,evidenceIds:[...n.evidenceIds]})),
   edges:(scene.edges||[]).map(e=>({...e,evidenceIds:[...e.evidenceIds]})),
   camera:{mode:'fit-bounds',safeArea:'presenter-right'},accessibility:{requiresTextAlternative:true}};
  return {ok:true,plan};
 }
}
export const sceneRegistry=new SceneRegistry();
